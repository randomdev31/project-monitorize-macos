"""Opt-in per-user controller unit. No root process or system-wide user settings."""
import base64
import json
import os
from pathlib import Path
import subprocess
import sys

UNIT='monitorize-remote-controller.service'
MARKER='# Generated by Monitorize remote login\n'


def _quote(value):
    value=str(value)
    if '\n' in value or '\r' in value or '\x00' in value:raise ValueError('Invalid controller path.')
    return '"'+value.replace('\\','\\\\').replace('"','\\"').replace('%','%%')+'"'


def unit_content(python=sys.executable,pythonpath=None):
    pythonpath=Path(__file__).resolve().parents[2] if pythonpath is None else pythonpath
    return MARKER+f'''[Unit]
Description=Monitorize remote-login desktop controller
PartOf=graphical-session.target
After=graphical-session-pre.target

[Service]
Type=simple
Slice=app.slice
ExecStart={_quote(python)} -m monitorize.desktop.controller_launcher
Environment={_quote('PYTHONPATH='+str(pythonpath))}
Restart=on-failure
RestartSec=3

[Install]
WantedBy=graphical-session.target
'''


def _run(args):
    result=subprocess.run(['/usr/bin/systemctl','--user',*args],capture_output=True,text=True,timeout=10)
    if result.returncode:raise RuntimeError('Could not configure the Monitorize desktop controller user service.')


def _read(path):
    try:
        fd=os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
        with os.fdopen(fd,'rb') as source:
            info=os.fstat(source.fileno())
            import stat
            if not stat.S_ISREG(info.st_mode) or info.st_uid!=os.getuid() or info.st_size>65536:raise ValueError('Unsafe controller settings file.')
            return source.read()
    except FileNotFoundError:return None


def _write(path,data):
    path.parent.mkdir(parents=True,exist_ok=True)
    temporary=path.with_name(path.name+'.monitorize-tmp')
    fd=os.open(temporary,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600)
    try:
        with os.fdopen(fd,'wb') as target:target.write(data)
        os.replace(temporary,path)
    finally:
        if temporary.exists():temporary.unlink()


def configure(enabled,*,config_home=None,run=_run):
    config=Path(config_home or os.environ.get('XDG_CONFIG_HOME',Path.home()/'.config'))
    unit=config/'systemd/user'/UNIT;backup=config/'monitorize/remote-login-controller-backup.json'
    desktop=config/'autostart/monitorize.desktop'
    if enabled:
        previous=_read(unit)
        if previous is not None and not previous.startswith(MARKER.encode()):raise ValueError('A custom controller unit already exists; it was left unchanged.')
        record=_read(backup)
        if record is None:
            data={'unit':None if previous is None else base64.b64encode(previous).decode(),
                  'autostart':None if (old:=_read(desktop)) is None else base64.b64encode(old).decode()}
            _write(backup,json.dumps(data).encode())
        content=unit_content().encode()
        try:
            _write(unit,content);run(['daemon-reload']);run(['enable',UNIT])
            # Avoid duplicate XDG and systemd starts on the next graphical login.
            if desktop.exists():desktop.unlink()
        except Exception:
            if previous is None:
                try:run(["disable",UNIT])
                except Exception:pass
            if previous is None:unit.unlink(missing_ok=True)
            else:_write(unit,previous)
            try:run(['daemon-reload'])
            except Exception:pass
            raise
    else:
        record=_read(backup)
        if record is None:return
        values=json.loads(record);run(['disable',UNIT])  # Never stop this GUI's own unit.
        current=_read(unit)
        if current is not None and not current.startswith(MARKER.encode()):raise ValueError('Controller unit was changed; restore it manually.')
        if values['unit'] is None:unit.unlink(missing_ok=True)
        else:_write(unit,base64.b64decode(values['unit'],validate=True))
        if not desktop.exists() and values['autostart'] is not None:
            _write(desktop,base64.b64decode(values['autostart'],validate=True))
        run(['daemon-reload']);backup.unlink()
